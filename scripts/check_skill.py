"""Check a skill the way a reader's agent will use it.

Two things are checked for every `docs/skills/<name>/SKILL.md`:

- the frontmatter an agent decides by: a `name` that matches the directory and a
  `description` that says what the skill is for and when to reach for it;
- the code. An agent pastes these blocks into a project, so they have to compile
  as written. A package is generated under `src/`, checked with the module's own
  settings, and removed again.

The blocks of one skill are compiled together, in order, as one package: a block
may use a name an earlier block defined, which is how the page reads.

Usage:
    python scripts/check_skill.py [--moon path/to/moon]
"""

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "docs" / "skills"
PACKAGE = ROOT / "src" / "skill_check"

HEADER = """// Generated by scripts/check_skill.py from docs/skills/{name}/SKILL.md.
"""


REQUIRED_FRONTMATTER = ("name", "description")


def frontmatter_of(text):
    """The YAML frontmatter lines, or `None` when the file has none."""
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---\n", 4)
    if end == -1:
        return None
    return text[4:end]


def frontmatter_problems(text, name):
    """Every reason a reader's agent would not find or trust this skill."""
    block = frontmatter_of(text)
    if block is None:
        return ["no frontmatter"]
    fields = {}
    for line in block.splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip().strip('"').strip("'")
    problems = [f"frontmatter has no {key}" for key in REQUIRED_FRONTMATTER if not fields.get(key)]
    if fields.get("name") and fields["name"] != name:
        problems.append(f"frontmatter name {fields['name']!r} is not the directory {name!r}")
    # The description is the whole basis for an agent deciding to read the file, so
    # a stub is as good as a missing one.
    if len(fields.get("description", "")) < 40:
        problems.append("description is too short to decide by")
    if not re.search(r"^## ", text, re.M):
        problems.append("no section")
    return problems


def blocks_of(text):
    return re.findall(r"```moonbit\n(.*?)```", text, re.S)


def defined_functions(code):
    """Every top-level `fn name` the blocks define, so the generated `main` can
    reference them: an unread function is a warning, and warnings fail the check."""
    return re.findall(r"^fn ([A-Za-z_][A-Za-z0-9_]*)", code, re.M)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--moon", default="moon")
    args = parser.parse_args()

    if not SKILLS.is_dir():
        print("no docs/skills directory", file=sys.stderr)
        return 1

    skills = sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file())
    if not skills:
        print("no skill to check", file=sys.stderr)
        return 1

    failed = 0
    for skill in skills:
        text = (skill / "SKILL.md").read_text(encoding="utf-8")
        problems = frontmatter_problems(text, skill.name)
        if problems:
            failed += 1
            for problem in problems:
                print(f"{skill.name}: {problem}", file=sys.stderr)
            continue
        code = "\n\n".join(blocks_of(text))
        if not code.strip():
            print(f"{skill.name}: no moonbit block", file=sys.stderr)
            failed += 1
            continue

        uses = "\n".join(f"  let _ = {name}" for name in defined_functions(code))
        program = HEADER.format(name=skill.name) + code + "\n\n///|\nfn main {\n" + uses + "\n}\n"

        shutil.rmtree(PACKAGE, ignore_errors=True)
        PACKAGE.mkdir(parents=True)
        (PACKAGE / "moon.pkg").write_text(
            'import {\n  "moonbitstack/moonzero",\n  "moonbitstack/moonapi",\n'
            '  "moonbitstack/moonrpc",\n}\n\npkgtype(kind: "executable")\n',
            encoding="utf-8",
            newline="\n",
        )
        (PACKAGE / "main.mbt").write_text(program, encoding="utf-8", newline="\n")

        try:
            result = subprocess.run(
                [args.moon, "check", "--deny-warn"],
                cwd=ROOT,
                capture_output=True,
                text=True,
            )
            if result.returncode == 0:
                print(f"{skill.name}: {len(blocks_of(text))} blocks compile")
            else:
                failed += 1
                print(f"{skill.name}: does not compile", file=sys.stderr)
                print(result.stdout + result.stderr, file=sys.stderr)
        finally:
            shutil.rmtree(PACKAGE, ignore_errors=True)

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
